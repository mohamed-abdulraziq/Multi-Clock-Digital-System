module Data_Sync_mohamed_abdulrazeq  #(parameter width = 8, NUM_STAGES = 2)
(
input  wire                clk,
input  wire                rst,
input  wire                Bus_En,
input  wire [(width-1):0]  Un_Sync_Bus,
output reg                 En_Pulse,
output reg  [(width-1):0]  Sync_Bus    
);

reg  [(NUM_STAGES-1):0]  DATA_SYNC ;
reg                 	 Pulse_Gen ;
wire                	 Pulse_Generated ;
wire [(width-1):0]  	 Sync_Bus_COMB ;
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////****Bus_En_Sync****///////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

always@(posedge clk or negedge rst)
  begin
    if (!rst)
      begin
        DATA_SYNC <= 'b0 ;
      end  
    else
      begin
        DATA_SYNC <= {DATA_SYNC[(NUM_STAGES-2):0], Bus_En} ;
      end
  end
  
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////****En_Pulse_Generation****///////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

always@(posedge clk or negedge rst)
  begin
    if (!rst)
      begin
        Pulse_Gen <= 1'b0 ;
      end
    else 
      begin
        Pulse_Gen <= DATA_SYNC[(NUM_STAGES-1)] ;
      end
  end
  
assign Pulse_Generated = DATA_SYNC[(NUM_STAGES-1)] && !Pulse_Gen ;

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////****MULTIPLIXING****//////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

assign Sync_Bus_COMB = Pulse_Generated ? Un_Sync_Bus : Sync_Bus ;

always@(posedge clk or negedge rst)
  begin
    if (!rst)
      begin
        Sync_Bus <= 'b0 ;
        En_Pulse <= 1'b0 ;
      end
    else 
      begin
        Sync_Bus <= Sync_Bus_COMB ;
        En_Pulse <= Pulse_Generated ;
      end    
  end
endmodule